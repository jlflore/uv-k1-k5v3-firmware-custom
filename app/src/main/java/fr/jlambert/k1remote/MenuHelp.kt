    /** Aide des autres écrans (n° = gScreenToDisplay du firmware Fusion). */
    fun screenHelp(screen: Int, menuLevel: Int): Pair<String, String> = when {
        screen == 1 && menuLevel == 0 -> "Catégories du menu" to
            "La radio range ses réglages par thème. ▲ ▼ pour choisir une catégorie, MENU pour l'ouvrir, EXIT pour sortir. La catégorie « All » contient tous les réglages, numérotés comme dans l'appli (ex. 40 Beep)."
        screen == 2 -> "Recherche de fréquence / sous-canal" to
            "La radio cherche la fréquence ou le sous-canal d'un émetteur proche. Faites émettre l'autre radio à moins d'un mètre. EXIT pour arrêter."
        screen == 3 -> "Radio FM" to
            "Écoute de la radio FM broadcast. ▲ ▼ pour changer de station, EXIT pour revenir. Pendant l'écoute FM, la radio continue de surveiller votre fréquence."
        screen == 4 -> "Journal des émissions et réceptions" to
            "Liste des derniers passages (heure, durée, fréquence). ▲ ▼ pour parcourir, EXIT pour revenir."
        else -> "Écran principal" to
            "Fréquence ou canal des lignes A et B, puissance, sous-canal, barre de signal. « Aide complète » détaille chaque indication."
    }
